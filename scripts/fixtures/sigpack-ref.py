# Reference values for the signal package (scripts/check-sigpack.ts reads sigpack-ref.json): the arPLS baseline
# (pybaselines), the change points (ruptures: Pelt and Binseg, jump 1), the continuous wavelet transform with its
# significance and the wavelet coherence (pycwt), the multiresolution analysis (PyWavelets' mra, the stationary
# transform), the peaks of a Ricker transform (SciPy's find_peaks_cwt), the fractional derivatives (differint, and the
# exact ones of powers), the fast fractional Fourier transform (fracF of Ozaktas et al. 1996, written out here), the
# Lomb–Scargle periodogram (astropy's LombScargle and scipy.signal.lombscargle), the Bessel filter and the notch
# (scipy.signal.bessel, iirnotch). It also writes src/engine/waveletFilters.ts (the filters of
# PyWavelets).
# Made with SciPy 1.18, PyWavelets 1.9, pycwt 0.5, pybaselines 1.2, ruptures 1.1, differint, astropy 8.0 (a virtual
# environment: pip install scipy PyWavelets pycwt pybaselines ruptures differint astropy).
import json, os, math
import numpy as np
from scipy import signal as ss
import pywt, pycwt, ruptures as rpt
from pybaselines import Baseline

HERE = os.path.dirname(__file__)
rng = np.random.default_rng(20261026)
out = {}

# ---- the wavelet filters ----
names = [f'db{i}' for i in range(1, 11)] + [f'sym{i}' for i in range(2, 11)] + [f'coif{i}' for i in range(1, 6)]
label = lambda n: ('Daubechies ' + n[2:]) if n.startswith('db') else ('Symlet ' + n[3:]) if n.startswith('sym') else ('Coiflet ' + n[4:])
lines = ['// The low-pass decomposition filters of the orthogonal wavelets (Daubechies 1–10, Symlets 2–10, Coiflets 1–5), as',
         '// PyWavelets (pywt.Wavelet(name).dec_lo; MIT): Σh = √2, Σh² = 1. Generated by scripts/fixtures/sigpack-ref.py.',
         'export const WAVELET_FILTERS: Record<string, { label: string; h: number[] }> = {']
for n in names:
    lines.append(f"  {n}: {{ label: '{label(n)}', h: [{', '.join(repr(float(v)) for v in pywt.Wavelet(n).dec_lo)}] }},")
lines.append('};')
open(os.path.join(HERE, '..', '..', 'src', 'engine', 'waveletFilters.ts'), 'w', encoding='utf-8').write('\n'.join(lines) + '\n')

# ---- arPLS ----
x = np.linspace(0, 100, 400)
y = 50 + 0.4 * x + 0.004 * (x - 40) ** 2 + 80 * np.exp(-((x - 30) ** 2) / 8) + 50 * np.exp(-((x - 70) ** 2) / 20) + rng.normal(0, 1.5, 400)
out['arpls'] = {'y': y.round(4).tolist(), 'b6': Baseline(x).arpls(y.round(4), lam=1e6)[0].tolist(), 'b4': Baseline(x).arpls(y.round(4), lam=1e4)[0].tolist()}

# ---- change points ----
lv = np.repeat([0.0, 3.0, 1.5, 4.0, 4.0 + 2.5], [80, 60, 90, 70, 100])
sig = lv + rng.normal(0, 0.8, len(lv))
sig2 = np.r_[rng.normal(0, 0.5, 150), rng.normal(0, 2.0, 150), rng.normal(1.0, 0.5, 120)]
out['steps'] = {'y': sig.round(4).tolist(), 'y2': sig2.round(4).tolist(),
                'pelt': rpt.Pelt(model='l2', min_size=5, jump=1).fit(sig.round(4)).predict(pen=20.0),
                'binseg': rpt.Binseg(model='l2', min_size=5, jump=1).fit(sig.round(4)).predict(pen=20.0),
                'binseg4': rpt.Binseg(model='l2', min_size=5, jump=1).fit(sig.round(4)).predict(n_bkps=4),
                'normal': rpt.Pelt(model='normal', min_size=5, jump=1).fit(sig2.round(4)).predict(pen=3 * math.log(len(sig2)))}

# ---- the continuous transform, its significance, the coherence ----
dt = 0.25
t = np.arange(0, 256) * dt
s1 = (np.sin(2 * np.pi * t / 8) * (t < 32) + np.sin(2 * np.pi * t / 3) * (t >= 24) + rng.normal(0, 0.5, len(t))).round(4)
s2 = (np.sin(2 * np.pi * t / 8 + 0.8) + rng.normal(0, 0.5, len(t))).round(4)
z1 = s1 - s1.mean()
res = {}
for name, mo in [('morlet', pycwt.Morlet(6)), ('paul', pycwt.Paul(4)), ('dog', pycwt.DOG(2))]:
    W, sj, freqs, coi, _, _ = pycwt.cwt(z1, dt, 1 / 8, -1, -1, mo)
    res[name] = {'scales': sj.tolist(), 'power': (np.abs(W) ** 2)[::7, ::17].tolist(), 'coi': coi[::17].tolist()}
alpha = float(np.sum((z1[1:]) * (z1[:-1])) / np.sum(z1 ** 2))
W, sj, freqs, coi, _, _ = pycwt.cwt(z1, dt, 1 / 8, -1, -1, pycwt.Morlet(6))
sig0, _ = pycwt.significance(np.var(z1), dt, sj, 0, alpha, significance_level=0.95, wavelet=pycwt.Morlet(6))
sig1, _ = pycwt.significance(np.var(z1), dt, sj, 1, alpha, significance_level=0.95, dof=len(z1) - sj, wavelet=pycwt.Morlet(6))
WCT, aWCT, coi2, freq2, _ = pycwt.wct(s1, s2, dt, dj=1 / 8, s0=-1, J=-1, sig=False, wavelet='morlet', normalize=True)
out['cwt'] = {'dt': dt, 'x': s1.tolist(), 'y': s2.tolist(), **res, 'alpha': alpha, 'sig0': sig0.tolist(), 'sig1': sig1.tolist(), 'wct': WCT[::7, ::17].tolist(), 'phase': aWCT[::7, ::17].tolist()}

# ---- the multiresolution analysis ----
xm = (np.cumsum(rng.normal(0, 1, 256)) + 3 * np.sin(np.arange(256) / 5)).round(4)
out['mra'] = {'x': xm.tolist(), **{w: [c.tolist() for c in pywt.mra(xm, w, level=4, transform='swt')] for w in ['db4', 'sym6', 'coif2', 'haar']}}

# ---- denoising (the thresholds written here, the transform of PyWavelets) ----
xd = np.sin(np.linspace(0, 8 * np.pi, 512)) * np.linspace(1, 3, 512) + (np.linspace(0, 1, 512) > 0.6) * 2
yd = (xd + rng.normal(0, 0.4, 512)).round(4)
def sure(d):
    n = len(d); univ = math.sqrt(2 * math.log(n)); s2 = (np.sum(d ** 2) - n) / n
    if s2 <= math.log2(n) ** 1.5 / math.sqrt(n): return univ
    a = np.sort(d ** 2); cum = np.cumsum(a); k = np.arange(n)
    risk = n - 2 * (k + 1) + cum + (n - k - 1) * a
    return min(math.sqrt(a[np.argmin(risk)]), univ)
def den(y, w, level, rule, mode, per):
    c = pywt.wavedec(y, w, mode='periodization', level=level)
    mad = lambda d: np.median(np.abs(d)) / 0.6745
    sf = mad(c[-1]); ts = []
    for l in range(1, len(c)):
        d = c[l]; s = mad(d) if per else sf
        if rule == 'universal': t = s * math.sqrt(2 * math.log(len(y)))
        elif rule == 'sure': t = s * sure(d / s)
        else:
            sx = math.sqrt(max(np.mean(d ** 2) - s * s, 0)); t = s * s / sx if sx > 0 else np.max(np.abs(d))
        ts.append(t); c[l] = pywt.threshold(d, t, mode=mode)
    return pywt.waverec(c, w, mode='periodization').tolist(), ts
out['denoise'] = {'y': yd.tolist(), **{f'{w}_{r}_{m}_{p}': den(yd, w, 5, r, m, p) for w in ['db4', 'sym8'] for r in ['universal', 'sure', 'bayes'] for m in ['soft', 'hard'] for p in [False, True]}}

# ---- peaks by the Ricker transform ----
xp = np.linspace(0, 100, 600)
yp = sum(a * np.exp(-((xp - c) ** 2) / (2 * w ** 2)) for a, c, w in [(5, 15, 1.2), (3, 32, 2.5), (6, 50, 1.5), (2.5, 66, 3), (4, 85, 2)]) + 0.3 * xp / 10 + rng.normal(0, 0.25, 600)
yp = yp.round(4)
out['peaks'] = {'y': yp.tolist(), 'widths': list(np.arange(1, 30)), 'peaks': ss.find_peaks_cwt(yp, np.arange(1, 30)).tolist()}

# ---- fractional calculus: the Grünwald–Letnikov sum written out; differint's RL (a trapezoid rule) ----
import differint.differint as dfi
xf = np.linspace(0, 1, 401); ff = xf ** 2 + np.sin(3 * xf); hf = xf[1]
def glsum(f, h, a):
    w = np.ones(len(f))
    for j in range(1, len(f)): w[j] = w[j - 1] * (j - 1 - a) / j
    return (h ** -a * np.convolve(w, f)[:len(f)]).tolist()
out['frac'] = {'x': xf.tolist(), 'f': ff.tolist(), 'gl': {str(a): glsum(ff, hf, a) for a in [0.5, -0.5, 1.3, -1.7]}, 'rl': {str(a): dfi.RL(a, ff, 0, 1, 401).tolist() for a in [0.5, -0.5]}}

# ---- the fast fractional Fourier transform: fracF of Ozaktas et al. (1996), written out again from its MATLAB ----
def fconv(x, y):
    N = len(x) + len(y) - 1; P = 1 << (N - 1).bit_length()
    return np.fft.ifft(np.fft.fft(x, P) * np.fft.fft(y, P))[:N]
def finterp(x):
    N = len(x); y = np.zeros(2 * N - 1, complex); y[::2] = x
    xi = fconv(y, np.sinc(np.arange(-(2 * N - 3), 2 * N - 2) / 2))
    return xi[2 * N - 3:len(xi) - 2 * N + 3]
def fracF(fc, a):
    fc = np.asarray(fc, complex).copy(); N = len(fc)
    shft = (np.arange(N) + N // 2) % N; sN = math.sqrt(N); a = a % 4
    def dft(v, inv):
        o = np.zeros(N, complex); o[shft] = np.fft.ifft(v[shft]) * sN if inv else np.fft.fft(v[shft]) / sN; return o
    if a == 0: return fc
    if a == 2: return fc[::-1]
    if a == 1: return dft(fc, False)
    if a == 3: return dft(fc, True)
    if a > 2: a -= 2; fc = fc[::-1].copy()
    if a > 1.5: a -= 1; fc = dft(fc, False)
    if a < 0.5: a += 1; fc = dft(fc, True)
    al = a * math.pi / 2; tana2 = math.tan(al / 2); sina = math.sin(al)
    f = np.concatenate([np.zeros(N - 1), finterp(fc), np.zeros(N - 1)])
    chrp = np.exp(-1j * math.pi / N * tana2 / 4 * np.arange(-2 * N + 2, 2 * N - 1) ** 2)
    f = chrp * f
    c = math.pi / N / sina / 4
    F = fconv(np.exp(1j * c * np.arange(-(4 * N - 4), 4 * N - 3) ** 2), f)
    F = F[4 * N - 4:8 * N - 7] * math.sqrt(c / math.pi)
    F = chrp * F
    return np.exp(-1j * (1 - a) * math.pi / 4) * F[N - 1:len(F) - N + 1:2]
zr = rng.normal(0, 1, 64); zi = rng.normal(0, 1, 64)
out['frft'] = {'re': zr.tolist(), 'im': zi.tolist(), **{str(a): [fracF(zr + 1j * zi, a).real.tolist(), fracF(zr + 1j * zi, a).imag.tolist()] for a in [0.3, 0.7, 1.2, 1.7, 2.6, 3.4, 1, 2]}}

# ---- the Lomb–Scargle periodogram: astropy (standard, the mean fitted; Baluev's false alarm) and SciPy ----
from astropy.timeseries import LombScargle
tl = np.sort(rng.uniform(0, 40, 160)).round(4)
yl = (1.3 + 0.8 * np.sin(2 * np.pi * tl / 3.7 + 0.4) + rng.normal(0, 0.6, 160)).round(4)
ls = LombScargle(tl, yl)
fl, pl = ls.autopower(samples_per_peak=5, nyquist_factor=1)
fap = ls.false_alarm_probability(pl.max(), method='baluev', maximum_frequency=fl.max())
lvl = ls.false_alarm_level(0.01, method='baluev', maximum_frequency=fl.max())
sp = ss.lombscargle(tl, yl, 2 * np.pi * fl, normalize=True, floating_mean=True)
out['lomb'] = {'t': tl.tolist(), 'y': yl.tolist(), 'f': fl.tolist(), 'power': pl.tolist(), 'scipy': sp.tolist(), 'fap': float(fap), 'level': float(lvl), 'fapAt': [float(ls.false_alarm_probability(z, method='baluev', maximum_frequency=fl.max())) for z in [0.05, 0.1, 0.2]]}

# ---- the Bessel filter (norm "phase", SciPy's default) and the notch: their responses at 64 frequencies ----
wq = np.linspace(0.001, 0.999, 64) * np.pi
def resp(sos): return ss.sosfreqz(sos, worN=wq)[1]
bes = {}
for N, bt, Wn in [(1, 'low', 0.2), (2, 'low', 0.2), (3, 'low', 0.3), (4, 'low', 0.25), (5, 'low', 0.1), (6, 'low', 0.4), (8, 'low', 0.2), (10, 'low', 0.3), (12, 'low', 0.2), (4, 'high', 0.3), (3, 'band', [0.1, 0.3]), (2, 'stop', [0.2, 0.35])]:
    h = resp(ss.bessel(N, Wn, btype=bt, output='sos'))
    bes[f'{N}_{bt}'] = {'N': N, 'band': bt, 'w': Wn if isinstance(Wn, list) else [Wn, 0], 're': h.real.tolist(), 'im': h.imag.tolist()}
nb, na = ss.iirnotch(50, 30, 1000)
hn = ss.freqz(nb, na, worN=wq)[1]
out['iir'] = {'w': (wq / (2 * np.pi)).tolist(), 'bessel': bes, 'notch': {'re': hn.real.tolist(), 'im': hn.imag.tolist()}}

with open(os.path.join(HERE, 'sigpack-ref.json'), 'w') as fh:
    fh.write(json.dumps(out, default=float).replace('NaN', 'null'))
print('ok')
